export function computeHeatIndex(tempC: number, rh: number): number {
  const tf = (tempC * 9) / 5 + 32;
  const hif = 0.5 * (tf + 61.0 + (tf - 68.0) * 1.2 + rh * 0.094);
  const hic = ((hif - 32) * 5) / 9;
  return Number(Math.max(tempC, hic).toFixed(1));
}

